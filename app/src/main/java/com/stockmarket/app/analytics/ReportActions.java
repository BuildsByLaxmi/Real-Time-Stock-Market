package com.stockmarket.app.analytics;

import android.app.Activity;
import android.content.ActivityNotFoundException;
import android.content.ContentResolver;
import android.content.ContentValues;
import android.content.Intent;
import android.net.Uri;
import android.os.Build;
import android.os.Environment;
import android.provider.MediaStore;
import android.view.View;
import android.widget.Toast;

import androidx.core.content.FileProvider;

import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;

/**
 * The "PDF", "Excel" and "Text" buttons on the chart and compare screens.
 * PDF and Excel are generated by the backend (/api/reports/...), saved to the phone's Downloads
 * folder (Android 10+) and opened. Plain text is shared through the share sheet; it falls back to a
 * locally built summary when the backend is down.
 */
public class ReportActions {

    public static final String PDF = "pdf";
    public static final String EXCEL = "excel";
    public static final String TEXT = "text";

    private final Activity activity;
    private final AnalyticsApi api;

    public ReportActions(Activity activity, AnalyticsApi api) {
        this.activity = activity;
        this.api = api;
    }

    /**
     * @param shown   what is on screen; used for the offline plain-text fallback
     * @param buttons disabled while the download runs, so a double tap does not start two downloads
     */
    public void export(String format, List<String> symbols, int bars, Comparison shown, View... buttons) {
        setEnabled(buttons, false);
        toast("Preparing " + label(format) + " report...");
        api.downloadReport(activity, format, symbols, bars, new AnalyticsApi.Callback<File>() {
            @Override
            public void onResult(File file) {
                setEnabled(buttons, true);
                if (activity.isFinishing()) return;
                if (TEXT.equals(format)) {
                    shareText(readText(file), file);
                } else {
                    String saved = saveToDownloads(file, mimeType(format));
                    if (saved != null) toast("Saved to Downloads/" + saved);
                    open(file, mimeType(format));
                }
            }

            @Override
            public void onError(String message) {
                setEnabled(buttons, true);
                if (activity.isFinishing()) return;
                if (TEXT.equals(format) && shown != null) {
                    toast("Server unavailable - sharing on-device summary");
                    shareText(TextReport.build(shown), null);
                } else {
                    Toast.makeText(activity, message, Toast.LENGTH_LONG).show();
                }
            }
        });
    }

    private void open(File file, String mime) {
        Uri uri = uriFor(file);
        Intent view = new Intent(Intent.ACTION_VIEW)
                .setDataAndType(uri, mime)
                .addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION);
        try {
            activity.startActivity(Intent.createChooser(view, "Open " + file.getName()));
        } catch (ActivityNotFoundException e) {
            share(uri, mime, file.getName());
        }
    }

    private void shareText(String text, File file) {
        Intent send = new Intent(Intent.ACTION_SEND)
                .setType("text/plain")
                .putExtra(Intent.EXTRA_SUBJECT, firstLine(text))
                .putExtra(Intent.EXTRA_TEXT, text);
        if (file != null) {
            send.putExtra(Intent.EXTRA_STREAM, uriFor(file)).addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION);
        }
        activity.startActivity(Intent.createChooser(send, "Share text report"));
    }

    private void share(Uri uri, String mime, String subject) {
        Intent send = new Intent(Intent.ACTION_SEND)
                .setType(mime)
                .putExtra(Intent.EXTRA_STREAM, uri)
                .putExtra(Intent.EXTRA_SUBJECT, subject)
                .addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION);
        try {
            activity.startActivity(Intent.createChooser(send, "Share " + subject));
        } catch (ActivityNotFoundException e) {
            toast("No app installed that can open this file");
        }
    }

    private Uri uriFor(File file) {
        return FileProvider.getUriForFile(activity, activity.getPackageName() + ".fileprovider", file);
    }

    /** Copies the file to the public Downloads folder. Android 10+ only (older versions need a storage permission). */
    private String saveToDownloads(File file, String mime) {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.Q) return null;
        ContentResolver resolver = activity.getContentResolver();
        ContentValues values = new ContentValues();
        values.put(MediaStore.Downloads.DISPLAY_NAME, file.getName());
        values.put(MediaStore.Downloads.MIME_TYPE, mime);
        values.put(MediaStore.Downloads.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS);
        values.put(MediaStore.Downloads.IS_PENDING, 1);
        Uri item = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values);
        if (item == null) return null;
        try (InputStream in = new FileInputStream(file); OutputStream out = resolver.openOutputStream(item)) {
            if (out == null) throw new IOException("No output stream");
            byte[] buf = new byte[8192];
            int n;
            while ((n = in.read(buf)) > 0) out.write(buf, 0, n);
        } catch (IOException e) {
            resolver.delete(item, null, null);
            return null;
        }
        values.clear();
        values.put(MediaStore.Downloads.IS_PENDING, 0);
        resolver.update(item, values, null, null);
        return file.getName();
    }

    private static String readText(File file) {
        try (InputStream in = new FileInputStream(file)) {
            byte[] buf = new byte[(int) Math.min(file.length(), 1_000_000)];
            int off = 0, n;
            while (off < buf.length && (n = in.read(buf, off, buf.length - off)) > 0) off += n;
            return new String(buf, 0, off, StandardCharsets.UTF_8);
        } catch (IOException e) {
            return "";
        }
    }

    private static String firstLine(String text) {
        int i = text.indexOf('\n');
        return i > 0 ? text.substring(0, i) : text;
    }

    private static String mimeType(String format) {
        if (PDF.equals(format)) return "application/pdf";
        if (EXCEL.equals(format)) return "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";
        return "text/plain";
    }

    private static String label(String format) {
        if (PDF.equals(format)) return "PDF";
        if (EXCEL.equals(format)) return "Excel";
        return "text";
    }

    private void toast(String message) {
        Toast.makeText(activity, message, Toast.LENGTH_SHORT).show();
    }

    private static void setEnabled(View[] views, boolean enabled) {
        for (View v : views) {
            if (v != null) {
                v.setEnabled(enabled);
                v.setAlpha(enabled ? 1f : 0.5f);
            }
        }
    }
}
